/** 固定业务窗口、原始记录保存与实际入选输入的隔离行为回归。 */
'use strict'
const assert = require('assert')
const fs = require('fs')
const os = require('os')
const path = require('path')
const { spawnSync } = require('child_process')
const ROOT = path.resolve(__dirname, '..', '..', '..')

// 用独立数据目录运行真实公共模块，避免配置和生产索引互相影响。
function runInputScenario(label, script, check, env = {}) {
  const dataDir = fs.mkdtempSync(path.join(os.tmpdir(), 'daily-report-input-'))
  try {
    const result = spawnSync(process.execPath, ['-e', script], { cwd: ROOT, env: { ...process.env, DONGXUELIAN_AI_DATA_DIR: dataDir, ...env }, encoding: 'utf8', timeout: 30000 })
    check(label, result.status === 0, result.stderr || result.stdout || String(result.error || ''))
  } finally {
    assert.ok(path.resolve(dataDir).startsWith(path.resolve(os.tmpdir()) + path.sep))
    fs.rmSync(dataDir, { recursive: true, force: true })
  }
}

